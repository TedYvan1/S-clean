-- Atomic server-side booking creation.
-- The advisory lock serializes bookings for a date.

create or replace function public.create_sclean_booking(
  p_booking_number text,
  p_user_id uuid,
  p_email text,
  p_customer_name text,
  p_phone text,
  p_vehicle text,
  p_service_id integer,
  p_date date,
  p_start_time time,
  p_address text,
  p_neighborhood text,
  p_landmark text default null
)
returns public.sclean_bookings
language plpgsql
security definer
set search_path = public
as $$
declare
  v_service public.sclean_services;
  v_zone_fee integer;
  v_end_time time;
  v_total integer;
  v_result public.sclean_bookings;
begin
  perform pg_advisory_xact_lock(
    hashtext('sclean-booking-' || p_date::text)
  );

  select *
  into v_service
  from public.sclean_services
  where id = p_service_id
    and active = true;

  if not found then
    raise exception 'SERVICE_UNAVAILABLE';
  end if;

  select coalesce(travel_fee, 0)
  into v_zone_fee
  from public.sclean_zones
  where name = p_neighborhood
    and active = true;

  if v_zone_fee is null then
    raise exception 'ZONE_UNAVAILABLE';
  end if;

  v_end_time :=
    p_start_time
    + make_interval(mins => v_service.duration_minutes);

  v_total := v_service.price + v_zone_fee;

  if
    p_start_time < time '08:00'
    or v_end_time > time '18:00'
    or (
      p_start_time < time '13:00'
      and v_end_time > time '12:00'
    )
  then
    raise exception 'OUTSIDE_HOURS';
  end if;

  if exists (
    select 1
    from public.sclean_bookings b
    where b.date = p_date
      and b.status <> 'cancelled'
      and b.start_time < v_end_time
      and b.end_time >
        (p_start_time - interval '30 minutes')
  ) then
    raise exception 'SLOT_UNAVAILABLE';
  end if;

  insert into public.sclean_bookings (
    booking_number,
    user_id,
    email,
    customer_name,
    phone,
    vehicle,
    service_id,
    service_name,
    date,
    start_time,
    end_time,
    address,
    neighborhood,
    landmark,
    total_price
  )
  values (
    p_booking_number,
    p_user_id,
    p_email,
    p_customer_name,
    p_phone,
    p_vehicle,
    p_service_id,
    v_service.name,
    p_date,
    p_start_time,
    v_end_time,
    p_address,
    p_neighborhood,
    p_landmark,
    v_total
  )
  returning *
  into v_result;

  return v_result;
end;
$$;

