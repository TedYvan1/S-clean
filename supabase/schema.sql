drop policy if exists "profiles_read_own"
on public.sclean_profiles;

create policy "profiles_read_own"
on public.sclean_profiles
for select
to authenticated
using (id = auth.uid());

drop policy if exists "services_public_read"
on public.sclean_services;

create policy "services_public_read"
on public.sclean_services
for select
to anon, authenticated
using (active = true);

drop policy if exists "zones_public_read"
on public.sclean_zones;

create policy "zones_public_read"
on public.sclean_zones
for select
to anon, authenticated
using (active = true);

drop policy if exists "bookings_read_own"
on public.sclean_bookings;

create policy "bookings_read_own"
on public.sclean_bookings
for select
to authenticated
using (user_id = auth.uid());

