-- S'Clean production schema: Supabase Auth + Postgres.
-- Apply in Supabase SQL Editor, then set the first admin role explicitly.

create table if not exists public.sclean_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  phone text,
  full_name text,
  role text not null default 'client'
    check (role in ('client', 'admin', 'staff')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.sclean_services (
  id integer generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  description text not null default '',
  price integer not null check (price > 0),
  duration_minutes integer not null
    check (duration_minutes > 0),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.sclean_zones (
  id integer generated by default as identity primary key,
  name text not null unique,
  travel_fee integer not null default 0
    check (travel_fee >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.sclean_availability (
  id integer generated by default as identity primary key,
  day_of_week integer not null
    check (day_of_week between 0 and 6),
  start_time time not null,
  end_time time not null,
  break_start time,
  break_end time,
  active boolean not null default true
);

create table if not exists public.sclean_blocked_slots (
  id integer generated by default as identity primary key,
  start_at timestamptz not null,
  end_at timestamptz not null,
  reason text not null,
  created_at timestamptz not null default now(),
  check (end_at > start_at)
);

create table if not exists public.sclean_bookings (
  booking_number text primary key,
  user_id uuid references auth.users(id)
    on delete set null,
  email text,
  customer_name text not null,
  phone text not null,
  vehicle text not null,
  service_id integer not null
    references public.sclean_services(id),
  service_name text not null,
  date date not null,
  start_time time not null,
  end_time time not null,
  address text not null,
  neighborhood text not null,
  landmark text,
  total_price integer not null
    check (total_price > 0),
  status text not null default 'confirmed'
    check (
      status in (
        'pending',
        'confirmed',
        'completed',
        'cancelled',
        'in_progress',
        'no_show'
      )
    ),
  payment_status text not null default 'unpaid'
    check (
      payment_status in (
        'unpaid',
        'partial',
        'paid'
      )
    ),
  created_at timestamptz not null default now()
);

create unique index if not exists
  sclean_bookings_slot_unique
on public.sclean_bookings(date, start_time)
where status <> 'cancelled';

create index if not exists
  sclean_bookings_user_id_idx
on public.sclean_bookings(user_id);

create index if not exists
  sclean_bookings_date_idx
on public.sclean_bookings(date, start_time);

